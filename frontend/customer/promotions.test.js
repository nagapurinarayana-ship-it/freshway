const assert = require('node:assert/strict');
const fs = require('node:fs');
const source = fs.readFileSync('frontend/customer/promotions.js', 'utf8');
const index = fs.readFileSync('index.html', 'utf8');
const sw = fs.readFileSync('sw.js', 'utf8');

assert.match(source, /INTERVAL=5000/);
assert.match(source, /pointerdown/);
assert.match(source, /pointerup/);
assert.match(source, /translate3d/);
assert.match(source, /object-fit:contain/);
assert.match(source, /max-height:38svh/);
assert.match(source, /aspect-ratio:4\/3/,'carousel must reserve the current production 4:3 banner frame before image decode');
assert.match(source, /sourceImage\.naturalWidth/);
assert.match(source, /sourceImage\.naturalHeight/);
assert.match(source, /viewport\.style\.aspectRatio/);
assert.match(source, /\.fw-promo-controls\{position:relative;/);
assert.doesNotMatch(source, /\.fw-promo-controls\{position:absolute/);
assert.doesNotMatch(source, /object-fit:cover/);
assert.match(source, /promotions\.length<2/);
assert.match(source, /FreshWayCustomerAPI\?\.request/);
assert.match(source, /p\?\.image_url/);
assert.doesNotMatch(index, /rel=\"preload\" href=\"\/api\/promotions\" as=\"fetch\"/, 'promotion metadata must not be double-fetched by a mismatched preload');
assert.match(source, /data-src=/);
assert.match(source, /loadSlideImage/);
assert.doesNotMatch(source, /data:'\+esc\(p\.image_mime_type\)/, 'public carousel markup must not embed promotion Base64 payloads');
assert.ok(index.includes('frontend/customer/promotions.js?v=20261030-lazy-promo-images-v1'), 'index must reference the full-image-fit customer banner asset');
assert.ok(sw.includes('/frontend/customer/promotions.js?v=20261030-lazy-promo-images-v1'), 'service worker must cache the full-image-fit customer banner asset');

assert.match(sw, /const CACHE = 'freshway-v[0-9]+'/);
console.log('customer promotion carousel: intrinsic-ratio responsive frame and complete promotional artwork OK');
