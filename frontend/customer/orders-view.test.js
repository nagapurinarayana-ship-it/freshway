const assert=require('node:assert/strict');
const vm=require('node:vm');
const context={window:{}};
vm.runInNewContext(require('node:fs').readFileSync('frontend/customer/orders-view.js','utf8'),context);
const api=context.window.FreshWayCustomerOrdersView;
assert.equal(typeof api.render,'function');
const el={innerHTML:''};
const document={querySelector(){return el}};
const helpers={esc:String,formatDate:String,money:n=>'₹'+n,statusLabel:String,planText:String};
api.render(document,[],helpers);
assert.match(el.innerHTML,/No orders yet/);
const base={createdAt:'2026-09-08',items:[],total:240,address:{house:'1',area:'A',city:'C',pincode:'123456'},payment:'Pending'};
api.render(document,[{...base,id:'FW-1',status:'New',deliveryPlan:'Today'}],helpers);
assert.match(el.innerHTML,/FW-1/);
assert.match(el.innerHTML,/Today/);
assert.match(el.innerHTML,/awaiting dispatch/);
assert.match(el.innerHTML,/invoice PDF will be available here after dispatch/i);
assert.doesNotMatch(el.innerHTML,/once invoice issuance is enabled/i);
api.render(document,[{...base,id:'FW-2',status:'Delivered',deliveryPlan:'Tomorrow'}],helpers);
assert.match(el.innerHTML,/class="status delivered">delivered/);
assert.match(el.innerHTML,/help with a dispatched order/i);
assert.doesNotMatch(el.innerHTML,/Tomorrow/);
api.render(document,[{...base,id:'FW-3',status:'Cancelled',deliveryPlan:'Today'}],helpers);
assert.match(el.innerHTML,/class="status cancelled">Cancelled/);
assert.doesNotMatch(el.innerHTML,/Today/);
api.render(document,[{...base,id:'FW-4',status:'delivered',deliveryPlan:'Later'}],helpers);
assert.match(el.innerHTML,/class="status delivered">Delivered/);
assert.doesNotMatch(el.innerHTML,/Later/);
console.log('customer orders-view terminal status tests OK');
